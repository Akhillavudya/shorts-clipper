"""Prompt templates on disk, read fresh on every call.

Two stages keep their prompts next to their code - ``moments/prompts/`` and
``discover/prompts/`` - and both want the same three things: read a template
verbatim, substitute placeholders, and list what is available. This is that
loader. Each package's ``__init__`` binds it to its own directory and re-exports
the functions, so callers still write ``prompts.render("rerank.user", ...)``.

Placeholders use ``string.Template`` (``$name``) rather than ``str.format``,
because these prompts are full of literal JSON braces and ``{"w": ...}`` in a
format string is an error waiting to happen at the worst moment - mid-run,
after the transcript has already been paid for.

Templates are read from disk on every call. A prompt edit takes effect on the
next run with no restart, which is the whole point of keeping them here. The
files are small; the read is not worth caching.

Note that a prompt change also changes the LLM cache key (``llm/cache.py``
hashes the prompt), so an edit correctly misses the cache rather than returning
a response generated by the previous wording.
"""

from __future__ import annotations

from pathlib import Path
from string import Template


class MissingPrompt(FileNotFoundError):
    """A named prompt file is not on disk."""


class PromptSet:
    """The ``.md`` prompt files in one directory."""

    def __init__(self, directory: Path | str) -> None:
        self.directory = Path(directory)

    def path(self, name: str) -> Path:
        """``"recall.system"`` -> ``<dir>/recall.system.md``."""
        return self.directory / f"{name}.md"

    def load(self, name: str) -> str:
        """Read a prompt template verbatim."""
        path = self.path(name)
        if not path.is_file():
            available = ", ".join(self.available())
            raise MissingPrompt(f"no prompt {name!r} at {path} (have: {available})")
        return path.read_text(encoding="utf-8")

    def render(self, name: str, **values: object) -> str:
        """Read a prompt and substitute ``$placeholders``.

        Uses ``substitute``, not ``safe_substitute``: an unfilled placeholder is
        a bug that should surface before the call is made, not a literal
        ``$words`` handed to a model that will do something confident and wrong
        with it.
        """
        return Template(self.load(name)).substitute(**values)

    def available(self) -> list[str]:
        """Names of every prompt on disk, for error messages and debugging."""
        return sorted(p.stem for p in self.directory.glob("*.md"))


__all__ = ["MissingPrompt", "PromptSet"]
